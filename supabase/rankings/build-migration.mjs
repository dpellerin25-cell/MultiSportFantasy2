// Offline only: builds a reviewable migration from the checked-in snapshots.
import {readFile,writeFile} from 'node:fs/promises';
const sqlString = value => "'" + String(value).replaceAll("'","''") + "'";
let sql = `-- Generated by supabase/rankings/build-migration.mjs. No external requests.
begin;
create function draft.ranking_name_key(value text) returns text
language sql immutable strict set search_path='' as $$
  select regexp_replace(normalize(translate(regexp_replace(lower(trim(value)), '\\s+(jr\\.?|sr\\.?|ii|iii|iv)$', ''), 'øłđðß', 'oldds'), NFKD), '[^a-z0-9]', '', 'g')
$$;
revoke all on function draft.ranking_name_key(text) from public,anon,authenticated;
create table draft.player_ranking_snapshot (
  sport text not null check(sport in ('NFL','MLB','NBA','EPL','PGA')),
  entry_number integer not null check(entry_number>0),
  player_name text not null,
  name_key text generated always as (draft.ranking_name_key(player_name)) stored,
  rank integer not null check(rank>0 and rank<2147483647),
  source_url text not null,
  ranking_type text not null,
  captured_on date not null,
  primary key(sport,entry_number)
);
alter table draft.player_ranking_snapshot enable row level security;
revoke all on draft.player_ranking_snapshot from public,anon,authenticated;
create index player_ranking_lookup on draft.player_ranking_snapshot(sport,name_key);
`;
for(const sport of ['NFL','MLB','NBA','EPL','PGA']) {
  const snapshot=JSON.parse(await readFile(new URL(`${sport.toLowerCase()}.json`,import.meta.url),'utf8'));
  if(snapshot.sport!==sport||snapshot.count!==snapshot.players.length||snapshot.captured_on!=='2026-09-29')throw Error('Invalid snapshot');
  const values=snapshot.players.map((p,i)=>{
    if(!Number.isSafeInteger(p.rank)||p.rank<1||!p.name?.trim())throw Error('Invalid ranking');
    return `(${[sport,i+1,p.name,p.rank,snapshot.source_url,snapshot.ranking_type,snapshot.captured_on].map(sqlString).join(',')})`;
  });
  sql+=`insert into draft.player_ranking_snapshot(sport,entry_number,player_name,rank,source_url,ranking_type,captured_on) values\n${values.join(',\n')};\n`;
}
sql+=await readFile(new URL('ranked-api.sql',import.meta.url),'utf8');
sql+='\ncommit;\n';
const path=new URL('../migrations/202609290001_player_ranking_snapshot.sql',import.meta.url);
if(process.argv.includes('--check')) {
  if(await readFile(path,'utf8')!==sql)throw Error('Ranking migration does not match snapshots');
  console.log('PASS ranking migration matches fixed snapshots');
} else {await writeFile(path,sql);console.log('Generated ranking snapshot migration locally.');}
